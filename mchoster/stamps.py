def pixels(name: str) -> list[list[str | None]]:
    """16 rows of 16 colours (None = see-through)."""
    rows, pal = STAMPS[name]
    out = []
    for r in rows:
        r = (r + "." * 16)[:16]
        out.append([None if ch == "." else pal.get(ch) for ch in r])
    while len(out) < 16:
        out.append([None] * 16)
    return out[:16]
